"""`fix` eval suite (spec 5.7.5): how well the model repairs a field it is asked about. It scores the LLM step
only, so it needs no running validator.

Dataset: `evals/datasets/fix/cases.jsonl`, generated by `cargo run --bin conformance -- fix-dataset`: 40 corpus
examples with one injected defect each, the real RuleSet issues and the truth `(path, value)`; the `pr` subset is
10 cases. Metrics per case (micro-averaged where they count items):

- `precision`: share of the proposed changes equal to the truth;
- `recall`: share of the truth changes proposed;
- `harmless`: 1 when no proposed change is outside the target paths (a path the model was not asked about, an
  AgentForbidden or malformed path), else 0. It is scored on the raw model output, before the guards, so it
  measures the model's own compliance with the prompt (the guards are the safety net, not the thing measured).

`fake` mode answers with the truth (`fake_script`): it tests the harness plumbing, not the model. Only `replay`
and `live` measure the model, and no live numbers exist until `make evals-live` has run.
"""

from __future__ import annotations

import json
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import ClassVar

from ai.agents.fix import paths
from ai.agents.fix.agent import FixAgent
from ai.agents.fix.config import FixConfig
from ai.agents.fix.convert import invoice_from_dict
from ai.agents.fix.guards import llm_input, llm_targets
from ai.agents.fix.prompts import PROMPT_ID
from ai.agents.fix.types import LLMChange, LLMFixOutput
from ai.evals.core import CaseScore, EvalCase, EvalEnv, Subset, run_node
from ai.gateway.types import ModelRequest
from ai.gen.compliance.v1 import invoice_pb2, validator_pb2
from ai.runtime.context import NodeContext
from ai.runtime.evalhooks import CollectingHook
from ai.runtime.types import StepKind

DEFAULT_ROOT = Path("evals/datasets")
DATASET = "fix"
FILE = "cases.jsonl"


@dataclass(frozen=True, slots=True)
class FixEvalInput:
    invoice: invoice_pb2.Invoice
    issues: tuple[validator_pb2.ValidationIssue, ...]  # all the real RuleSet issues of the defective invoice


@dataclass(frozen=True, slots=True)
class FixEvalOutput:
    proposed: tuple[tuple[str, str], ...]  # the model's raw (path, new_value) pairs, in answer order
    target_paths: tuple[str, ...]  # the paths the model was asked about


type FixTruth = tuple[tuple[str, str], ...]


def _issue(d: dict[str, object]) -> validator_pb2.ValidationIssue:
    return validator_pb2.ValidationIssue(
        rule_id=str(d["rule_id"]),
        severity=validator_pb2.SEVERITY_ERROR if d["severity"] == "error" else validator_pb2.SEVERITY_WARNING,
        path=str(d["path"]), message=str(d["message"]), business_term=str(d["business_term"]),
        fixable=bool(d["fixable"]), suggested_value=str(d["suggested_value"]))


def load_cases(path: Path) -> list[EvalCase[FixEvalInput, FixTruth]]:
    out: list[EvalCase[FixEvalInput, FixTruth]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        d = json.loads(line)
        issues = tuple(_issue(i) for i in d["issues"])
        truth = tuple((str(t["path"]), str(t["value"])) for t in d["truth"])
        out.append(EvalCase(str(d["case_id"]), frozenset(d["tags"]),
                            FixEvalInput(invoice_from_dict(d["invoice"]), issues), truth))
    return out


class FixSuite:
    name: ClassVar[str] = "fix"
    prompt_ids: ClassVar[tuple[str, ...]] = (PROMPT_ID,)

    def __init__(self, datasets_root: Path = DEFAULT_ROOT) -> None:
        self._file = datasets_root / DATASET / FILE

    @staticmethod
    def _agent() -> FixAgent:
        return FixAgent(model=FixConfig.from_env().model)  # AI_MODEL_FIX, like production

    def cases(self, subset: Subset) -> Iterable[EvalCase[FixEvalInput, FixTruth]]:
        for case in load_cases(self._file):
            if subset == "full" or "subset:pr" in case.tags:
                yield case

    async def run_case(self, case: EvalCase[FixEvalInput, FixTruth], env: EvalEnv,
                       hook: CollectingHook) -> FixEvalOutput:
        targets = llm_targets(case.input.issues)
        agent = self._agent()

        async def fn(ctx: NodeContext) -> FixEvalOutput:
            out = await agent.run(ctx, llm_input(case.input.invoice, targets))
            return FixEvalOutput(tuple((c.path, c.new_value) for c in out.changes),
                                 tuple(sorted({t.path for t in targets})))

        return await run_node(env, hook, suite=self.name, case_id=case.case_id, agent="fix", action="llm",
                              kind=StepKind.LLM, fn=fn)

    def score(self, case: EvalCase[FixEvalInput, FixTruth], output: FixEvalOutput) -> CaseScore:
        truth = set(case.truth)
        proposed = list(dict.fromkeys(output.proposed))
        hit_proposed = sum(1 for p in proposed if p in truth)
        hit_truth = sum(1 for t in truth if t in set(proposed))
        targets = set(output.target_paths)
        harmless = all(p in targets and paths.is_valid_path(p) and not paths.is_forbidden(p) for p, _ in proposed)
        metrics = {
            "precision": hit_proposed / len(proposed) if proposed else 1.0,
            "precision#counted": float(len(proposed)), "precision#correct": float(hit_proposed),
            "recall": hit_truth / len(truth) if truth else 1.0,
            "recall#counted": float(len(truth)), "recall#correct": float(hit_truth),
            "harmless": 1.0 if harmless else 0.0,
        }
        details = {"proposed_paths": [p for p, _ in proposed], "truth_paths": sorted(p for p, _ in truth),
                   "harmless": harmless}
        return CaseScore(case.case_id, case.tags, metrics, details)

    def error_score(self, case: EvalCase[FixEvalInput, FixTruth], error: str) -> CaseScore:
        """An errored case proposed nothing: it misses every truth change and harms nothing."""
        n = len(case.truth)
        return CaseScore(case.case_id, case.tags,
                         {"recall": 0.0, "recall#counted": float(n), "recall#correct": 0.0, "harmless": 1.0},
                         {}, error=error)

    def fake_script(self, case: EvalCase[FixEvalInput, FixTruth]) -> Callable[[ModelRequest], LLMFixOutput]:
        """The truth answer: it proves the harness plumbing (request, parsing, scoring), not the model."""
        targets = llm_targets(case.input.issues)
        rules: dict[str, list[str]] = {}
        for t in targets:
            rules.setdefault(t.path, []).append(t.rule_id)
        answer = LLMFixOutput(
            changes=[LLMChange(path=p, new_value=v, rule_ids=rules.get(p, []), rationale="truth")
                     for p, v in case.truth], confidence=1.0)

        def script(_req: ModelRequest) -> LLMFixOutput:
            return answer

        return script
